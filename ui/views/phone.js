// Pairing page for the phone remote: a big QR code and what the phone can do.

import { api } from '../core/api.js';
import { el } from '../core/dom.js';
import { attempt } from '../core/feedback.js';
import { currentView, render } from '../core/nav.js';
import { t } from '../core/i18n.js';
import { admitProtectedChange } from '../core/lock-rules.js';
import { pairingNeedsParent } from '../core/net-rules.js';
import { ensureParentGrant, parental, refreshParental } from '../components/parental.js';
import { ensureUnlocked } from '../components/passcode.js';

export function pairingPage() {
  return {
    id: 'pairing',
    get name() { return t('phone.title'); },
    info: null,
    async load(newCode = false) {
      this.info = (await attempt(() => api.getRemote(newCode), t('phone.unavailable'))) ?? { enabled: false };
      if (currentView() === this) render();
    },
    build(root) {
      if (!this.info) {
        this.load();
        root.append(el('p', { className: 'empty-note', textContent: t('phone.loading') }));
        return;
      }
      const r = this.info;
      const qr = el('div', { className: 'pair-qr' });
      if (r.qr) qr.innerHTML = r.qr; // SVG generated by the host from our own URL
      root.append(el('div', { className: 'pairing' },
        r.qr ? qr : el('div', { className: 'pair-qr pair-off', textContent: r.pairLocked ? t('phone.pairLocked') : r.codeHidden ? t('phone.codeHidden') : r.enabled ? t('phone.noNetwork') : t('phone.off') }),
        el('div', { className: 'pair-text' },
          el('h2', { textContent: t('phone.heading') }),
          el('ol', { className: 'pair-steps' },
            el('li', { textContent: t('phone.step1') }),
            el('li', { textContent: t('phone.step2') }),
            el('li', { textContent: t('phone.step3') })),
          // The pairing secret is only in the QR code (the link's fragment), never as text on the screen.
          r.qr ? el('p', { className: 'meta pair-code', textContent: t('phone.code', { address: r.address }) }) : null,
          r.pairLocked ? el('p', { className: 'meta', textContent: t('phone.pairLockedHint') }) : null,
          el('p', { className: 'meta', textContent: r.devices?.length ? t('phone.paired', { names: r.devices.map((d) => d.name).join(', ') }) : t('phone.noneYet') }))));
    },
    /**
     * A new code: with parental controls on the unlock and then the parents' code for exactly this pairing come first, before the host makes the
     * code (it asks for the same grant). Cancelling shows nothing and changes nothing.
     */
    async newCode() {
      const parentalOn = !!(parental.status ?? (await refreshParental()))?.enabled;
      if (pairingNeedsParent(true, parentalOn)
        && !(await admitProtectedChange({
          reason: t('phone.parentReason'), parentalOn, scope: { action: 'remotePair' }, ensureUnlocked, ensureParentGrant
        }))) return;
      await this.load(true);
    },
    /** Leaving the page: the host stops showing (and, with parental controls on, honouring) the code made for it. */
    onClose() {
      api.leavePairing?.()?.catch?.(() => {});
    },
    handle(action) {
      if (action === 'x') this.newCode();
    },
    hints() {
      return [['X', t('phone.hint.newCode')], ['B', t('phone.hint.back')]];
    }
  };
}
