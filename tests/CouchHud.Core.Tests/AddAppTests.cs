/// <summary>Adding an app from the Start menu list, startup parameters and working folder of own entries.</summary>
public class AddAppTests
{
    private const string Win = @"C:\Windows";
    private const string Notes = "Contoso.Notes_8wekyb3d8bbwe!App";

    private static string? Folders(string guid) => guid.Equals("6D809377-6AF0-444B-8957-A3773F02200E", StringComparison.OrdinalIgnoreCase) ? @"C:\Program Files" : null;

    // ----- the apps folder list -----

    [Fact]
    public void Clean_drops_duplicates_documents_uninstallers_and_CouchHud_and_sorts_A_to_Z()
    {
        var cleaned = InstalledApps.Clean(
        [
            new("Terminal", "Microsoft.WindowsTerminal_8wekyb3d8bbwe!App"),
            new("notes", Notes),
            new("Notes", Notes.ToLowerInvariant()),               // same name again: one is enough
            new("Notes (Store)", Notes),                           // same id again
            new("Benutzerhandbuch", @"C:\Programme\WinMerge\Docs\WinMerge.chm"),
            new("Uninstall Foo", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Foo\unins000.exe"),
            new("Foo deinstallieren", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Foo\unins001.exe"),
            new("Readme", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Foo\readme.txt"),
            new("CouchHUD", @"C:\Program Files\CouchHud\CouchHud.Shell.exe"),
            new("  ", "x"),
            new("Ohne Id", ""),
            new("Notepad++", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Notepad++\notepad++.exe"),
            new("ärger", "ai.example.aerger")
        ], StringComparer.OrdinalIgnoreCase);

        Assert.Equal(["Notepad++", "notes", "Terminal", "ärger"], cleaned.Select(a => a.Name));
        Assert.Equal(4, cleaned.Count);
        Assert.Single(cleaned, a => a.Id.Equals(Notes, StringComparison.OrdinalIgnoreCase));
        Assert.DoesNotContain(cleaned, a => a.Name.Contains("Uninstall") || a.Name.Contains("deinstallieren") || a.Name == "Readme" || a.Name == "Benutzerhandbuch");
    }

    [Theory]
    [InlineData("Contoso.Notes_8wekyb3d8bbwe!App", true)]
    [InlineData("Microsoft.WindowsTerminal_8wekyb3d8bbwe!App", true)]
    [InlineData("ai.storyteller.artcraft-launcher", false)]
    [InlineData("Microsoft.AutoGenerated.{B2F0E6BC-2A75-F06F-D7A8-228F7CED9DAA}", false)]
    [InlineData(@"C:\x\a!b.exe", false)]
    [InlineData("a!b\r\nc", false)]
    [InlineData("", false)]
    public void Only_package_ids_go_through_the_activation_manager(string id, bool packaged) =>
        Assert.Equal(packaged, InstalledApps.IsPackagedId(id));

    [Fact]
    public void A_store_app_becomes_a_shell_apps_folder_entry()
    {
        var entry = InstalledApps.ToEntry(new("Notes", Notes), "app", Folders, _ => true);
        Assert.Equal(@"shell:AppsFolder\Contoso.Notes_8wekyb3d8bbwe!App", entry.Url);
        Assert.Null(entry.Path);
        Assert.Equal("app", entry.Type);
    }

    [Fact]
    public void A_classic_program_becomes_an_exe_entry_when_its_file_exists()
    {
        var app = new InstalledApp("Notepad++", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Notepad++\notepad++.exe");
        var found = InstalledApps.ToEntry(app, "app", Folders, p => p == @"C:\Program Files\Notepad++\notepad++.exe");
        Assert.Equal(@"C:\Program Files\Notepad++\notepad++.exe", found.Path);
        Assert.Null(found.Url);

        var gone = InstalledApps.ToEntry(app, "app", Folders, _ => false);
        Assert.Equal(@"shell:AppsFolder\{6D809377-6AF0-444B-8957-A3773F02200E}\Notepad++\notepad++.exe", gone.Url);

        var direct = InstalledApps.ToEntry(new("Tool", @"D:\Tools\tool.exe"), "app", Folders, _ => true);
        Assert.Equal(@"D:\Tools\tool.exe", direct.Path);
    }

    [Fact]
    public void Apps_already_in_the_library_are_marked()
    {
        LibraryItem Item(string id, LaunchKind kind, string target) => new() { Id = id, Source = "custom", Name = id, Type = ItemType.App, Launch = new LaunchTarget(kind, target) };
        var marked = InstalledApps.MarkKnown(
            [new("Notes", Notes), new("Notepad++", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Notepad++\notepad++.exe"), new("Terminal", "Microsoft.WindowsTerminal_8wekyb3d8bbwe!App")],
            [Item("custom:notes", LaunchKind.Url, @"SHELL:appsfolder\Contoso.Notes_8wekyb3d8bbwe!App"), Item("custom:n", LaunchKind.Exe, @"c:\program files\notepad++\NOTEPAD++.EXE")],
            Folders, _ => true);

        Assert.Equal([true, true, false], marked.Select(a => a.Known));
    }

    // ----- start plan -----

    [Fact]
    public void An_exe_start_has_program_arguments_and_folder_as_separate_fields()
    {
        var target = new LaunchTarget(LaunchKind.Exe, @"C:\Users\x\AppData\Local\Microsoft\WindowsApps\wt.exe")
        {
            Args = ["-d", @"D:\my projects", "devtool", "--resume"],
            WorkingDirectory = @"D:\projects\app"
        };
        var plan = LaunchOptions.Plan(target, _ => true);

        Assert.Equal(target.Target, plan.FileName);
        Assert.Equal(@"-d ""D:\my projects"" devtool --resume", plan.Arguments);
        Assert.Equal(@"D:\projects\app", plan.WorkingDirectory);
        Assert.Null(plan.PackagedAppId);
    }

    [Fact]
    public void Arguments_with_shell_characters_stay_one_argument_each()
    {
        var plan = LaunchOptions.Plan(new LaunchTarget(LaunchKind.Exe, @"D:\a.exe") { Args = ["a & calc", "b|c", "\"q\""] }, _ => true);
        Assert.Equal(@"""a & calc"" b|c ""\""q\""""", plan.Arguments);
    }

    [Fact]
    public void A_store_app_start_names_the_package_a_classic_one_does_not()
    {
        var store = LaunchOptions.Plan(new LaunchTarget(LaunchKind.Url, @"shell:AppsFolder\" + Notes));
        Assert.Equal(Notes, store.PackagedAppId);
        Assert.Equal(@"shell:AppsFolder\" + Notes, store.FileName);

        var classic = LaunchOptions.Plan(new LaunchTarget(LaunchKind.Url, @"shell:AppsFolder\ai.storyteller.artcraft-launcher"));
        Assert.Null(classic.PackagedAppId);

        var web = LaunchOptions.Plan(new LaunchTarget(LaunchKind.Url, "https://example.com"));
        Assert.Null(web.PackagedAppId);
        Assert.Equal("", web.Arguments);
    }

    [Fact]
    public void A_working_folder_that_has_gone_stops_the_start()
    {
        var target = new LaunchTarget(LaunchKind.Exe, @"D:\a.exe") { WorkingDirectory = @"D:\gone" };
        Assert.Throws<InvalidOperationException>(() => LaunchOptions.Plan(target, _ => false));
    }

    [Theory]
    [InlineData(@"-d D:\projects\app devtool --resume", 4)]
    [InlineData(@"--name ""My Game"" -windowed", 3)]
    [InlineData("", 0)]
    [InlineData("   ", 0)]
    public void Typed_arguments_split_like_a_command_line(string text, int count) => Assert.Equal(count, LaunchOptions.ParseArguments(text).Count);

    [Fact]
    public void Arguments_survive_a_round_trip_through_the_edit_field()
    {
        string[] args = ["-d", @"D:\my folder\", "devtool", "--resume", "a\"b"];
        Assert.Equal(args, LaunchOptions.ParseArguments(LaunchOptions.FormatArguments(args)));
    }

    [Theory]
    [InlineData("a\nb")]
    [InlineData("a\0b")]
    public void Arguments_with_control_characters_are_refused(string text) => Assert.Throws<ArgumentException>(() => LaunchOptions.ParseArguments(text));

    [Fact]
    public void Overlong_arguments_are_refused() =>
        Assert.Throws<ArgumentException>(() => LaunchOptions.ParseArguments(new string('x', LaunchOptions.MaxArgumentsLength + 1)));

    // ----- working folder -----

    [Fact]
    public void The_working_folder_must_exist_and_be_absolute()
    {
        Assert.Null(LaunchOptions.ValidateWorkingDirectory("", @"D:\a\a.exe"));
        Assert.Null(LaunchOptions.ValidateWorkingDirectory("  ", @"D:\a\a.exe"));
        Assert.Equal(@"D:\projects\app", LaunchOptions.ValidateWorkingDirectory(@"""D:\projects\app""", @"D:\a\a.exe", _ => true));
        Assert.Throws<ArgumentException>(() => LaunchOptions.ValidateWorkingDirectory(@"D:\nope", @"D:\a\a.exe", _ => false));
        Assert.Throws<ArgumentException>(() => LaunchOptions.ValidateWorkingDirectory(@"relative\dir", @"D:\a\a.exe", _ => true));
        Assert.Throws<ArgumentException>(() => LaunchOptions.ValidateWorkingDirectory("D:\\a\nb", @"D:\a\a.exe", _ => true));
    }

    [Fact]
    public void The_programs_own_folder_is_stored_as_the_default()
    {
        Assert.Null(LaunchOptions.ValidateWorkingDirectory(@"d:\A\", @"D:\a\a.exe", _ => true));
        Assert.Equal(@"D:\a\sub", LaunchOptions.ValidateWorkingDirectory(@"D:\a\sub", @"D:\a\a.exe", _ => true));
    }

    // ----- entries in the library -----

    [Fact]
    public void The_install_folder_is_the_programs_not_the_working_folder()
    {
        var item = CustomEntries.From([new CustomEntry { Name = "Dev shell", Type = "app", Path = @"C:\Users\x\.local\bin\devtool.exe", Args = ["--resume"], Cwd = @"D:\projects\app" }]).Single();

        Assert.Equal(@"C:\Users\x\.local\bin", item.InstallDir);
        Assert.Equal(@"D:\projects\app", item.Launch.WorkingDirectory);
        Assert.Equal(["--resume"], item.Launch.Args);
    }

    [Fact]
    public void Without_a_working_folder_the_program_runs_in_its_own()
    {
        var item = CustomEntries.From([new CustomEntry { Name = "Kodi", Path = @"C:\Kodi\kodi.exe" }]).Single();
        Assert.Equal(@"C:\Kodi", item.Launch.WorkingDirectory);
        Assert.Equal(@"C:\Kodi", item.InstallDir);
    }

    [Fact]
    public void Store_app_aliases_have_no_install_folder_that_would_match_every_stub()
    {
        var aliases = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Microsoft", "WindowsApps", "wt.exe");
        var item = CustomEntries.From([new CustomEntry { Name = "Terminal", Path = aliases, Args = ["-d", @"D:\projects\app"] }]).Single();
        Assert.Null(item.InstallDir);
        Assert.False(GameSessionTracker.CanDetect(item));
    }

    [Fact]
    public void A_store_app_entry_has_no_process_to_watch_so_it_is_never_shown_as_running()
    {
        var item = CustomEntries.From([new CustomEntry { Name = "Notes", Type = "app", Url = @"shell:AppsFolder\" + Notes }]).Single();
        Assert.Null(item.InstallDir);
        Assert.False(GameSessionTracker.CanDetect(item));
    }

