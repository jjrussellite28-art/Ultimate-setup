    // ----- editing -----

    private static (LibraryService Service, ConfigStore Config, string Dir) Library(params CustomEntry[] entries)
    {
        var dir = Directory.CreateTempSubdirectory("couchhud-addapp-").FullName;
        var config = new ConfigStore(dir);
        config.Update(c => c.Apps = [.. entries]);
        var resolver = new ArtworkResolver(new HttpClient(), Path.Combine(dir, "art.json"), null);
        return (new LibraryService(config, resolver, []), config, dir);
    }

    [Fact]
    public async Task Editing_the_launch_saves_arguments_and_folder_and_updates_the_item()
    {
        var work = Directory.CreateTempSubdirectory("couchhud-cwd-").FullName;
        var (service, config, _) = Library(new CustomEntry { Name = "Dev shell", Type = "app", Path = @"C:\Users\x\.local\bin\devtool.exe" });
        var items = await service.ScanAsync();
        var id = items.Single().Id;

        var edited = service.EditLaunch(id, "--resume", work);

        Assert.Equal(["--resume"], edited.Launch.Args);
        Assert.Equal(Path.GetFullPath(work), edited.Launch.WorkingDirectory);
        Assert.Equal(@"C:\Users\x\.local\bin", edited.InstallDir);
        var saved = config.Current.Apps.Single();
        Assert.Equal(["--resume"], saved.Args);
        Assert.Equal(Path.GetFullPath(work), saved.Cwd);
        Assert.Equal(["--resume"], service.Find(id)!.Launch.Args);
    }

    [Fact]
    public async Task Editing_the_launch_refuses_a_missing_folder_and_keeps_the_old_values()
    {
        var (service, config, _) = Library(new CustomEntry { Name = "Tool", Path = @"C:\Tools\tool.exe", Args = ["-a"] });
        var id = (await service.ScanAsync()).Single().Id;

        Assert.Throws<ArgumentException>(() => service.EditLaunch(id, "-b", @"Z:\definitely\not\here"));

        Assert.Equal(["-a"], config.Current.Apps.Single().Args);
        Assert.Equal(["-a"], service.Find(id)!.Launch.Args);
    }

    [Fact]
    public async Task Editing_the_launch_only_works_for_own_exe_entries()
    {
        var (service, _, _) = Library(new CustomEntry { Name = "Site", Url = "https://example.com" });
        var id = (await service.ScanAsync()).Single().Id;
        Assert.Throws<KeyNotFoundException>(() => service.EditLaunch(id, "-x", null));
        Assert.Throws<KeyNotFoundException>(() => service.EditLaunch("steam:1", "-x", null));
    }

    [Fact]
    public async Task Clearing_the_fields_goes_back_to_the_default()
    {
        var (service, config, _) = Library(new CustomEntry { Name = "Tool", Path = @"C:\Tools\tool.exe", Args = ["-a"], Cwd = Path.GetTempPath() });
        var id = (await service.ScanAsync()).Single().Id;

        var edited = service.EditLaunch(id, "", "");

        Assert.Empty(edited.Launch.Args);
        Assert.Equal(@"C:\Tools", edited.Launch.WorkingDirectory);
        Assert.Null(config.Current.Apps.Single().Cwd);
    }

    [Fact]
    public void The_assistant_and_MCP_cannot_set_parameters_or_a_folder_when_editing_and_adding_is_confirmed()
    {
        var edit = CouchHud.Core.Assistant.ToolCatalog.All.Single(t => t.Name == "edit_item");
        var props = edit.Schema["properties"]!.AsObject().Select(p => p.Key).ToList();
        Assert.DoesNotContain("args", props);
        Assert.DoesNotContain("cwd", props);
        Assert.DoesNotContain("arguments", props);
        Assert.DoesNotContain("workingDirectory", props);

        var add = CouchHud.Core.Assistant.ToolCatalog.All.Single(t => t.Name == "add_entry");
        Assert.Contains("args", add.Schema["properties"]!.AsObject().Select(p => p.Key));
        Assert.True(add.NeedsConfirmationOverMcp);
        Assert.False(CouchHud.Core.Assistant.ToolCatalog.AllowedWhileLocked("add_entry"));
        Assert.True(CouchHud.Core.Assistant.ToolCatalog.IsDangerous("add_entry"));
    }
